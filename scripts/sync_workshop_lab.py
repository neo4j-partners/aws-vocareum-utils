#!/usr/bin/env -S uv run
# /// script
# requires-python = ">=3.11"
# ///
"""Publish `src/workshop_lab/` into the public workshop repository.

The lab notebook installs its utility classes with pip from a public GitHub
archive, because helper files shipped beside a notebook do not reach a Vocareum
workspace (measured 2026-08-06) and a raw fetch does. `aws-vocareum` is private,
and a private repository answers both the raw and the archive endpoint with 404
rather than 403, so the copy the notebook installs cannot live here.

That leaves one package in two repositories, and a hand-kept copy drifts. This
writes one into the other, the same shape as `lab-probe.template`'s inline
Lambda source and its drift test, and `tests/runtime/test_workshop_lab_drift.py` fails
when the published copy disagrees with the source.

    ./scripts/sync_workshop_lab.py                 # publish
    ./scripts/sync_workshop_lab.py --check         # exit 1 when stale
    ./scripts/sync_workshop_lab.py --target DIR    # publish somewhere else

The destination defaults to a sibling checkout of the workshop repository. It is
a path rather than a git push on purpose: this script only writes files, and
what gets committed and when stays a human decision.
"""

import argparse
import sys
from pathlib import Path

REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPOSITORY_ROOT / "src" / "workshop_lab"

# A sibling checkout, which is how both repositories are laid out on the machines
# that run this. --target overrides it.
DEFAULT_TARGET = (
    REPOSITORY_ROOT.parent / "neo4j-sec-filings-graphrag-workshop" / "staging"
)

PACKAGE = "workshop_lab"

# Written beside the package so `pip install <archive>#subdirectory=staging`
# has something to build. Kept here rather than in the workshop repository so
# the published tree is entirely generated and nothing there needs hand-editing.
PYPROJECT = """\
# This file is generated by aws-vocareum/scripts/sync_workshop_lab.py.
# Edit it there. Editing it here is overwritten on the next sync.
[build-system]
requires = ["setuptools>=68"]
build-backend = "setuptools.build_meta"

[project]
name = "workshop-lab"
version = "{version}"
description = "Utility classes for the Neo4j AWS workshop lab notebooks"
requires-python = ">=3.10"
dependencies = [
    "boto3>=1.34",
    "botocore>=1.34",
]

[tool.setuptools.packages.find]
include = ["workshop_lab*"]
"""

HEADER = """\
# This file is generated. Editing it here is wasted work.
#
# Source:     aws-vocareum/src/workshop_lab/{name}
# Regenerate: ./scripts/sync_workshop_lab.py
#
# tests/test_workshop_lab_drift.py fails when the copies disagree.
"""


def source_files() -> list[Path]:
    """Every module in the package, sorted so the output is stable."""
    return sorted(path for path in SOURCE.glob("*.py"))


def package_version() -> str:
    """Read `__version__` out of the package without importing it.

    Importing would pull in boto3, which this script has no reason to require.
    """
    for line in (SOURCE / "__init__.py").read_text(encoding="utf-8").splitlines():
        if line.startswith("__version__"):
            return line.split("=", 1)[1].strip().strip('"').strip("'")
    raise SystemExit("src/workshop_lab/__init__.py declares no __version__")


def published_text(path: Path) -> str:
    """The exact text the published copy of one module should hold."""
    return HEADER.format(name=path.name) + path.read_text(encoding="utf-8")


def plan(target: Path) -> tuple[dict[Path, str], list[Path]]:
    """Return the files to write and the stale ones to delete."""
    package_dir = target / PACKAGE
    wanted: dict[Path, str] = {
        target / "pyproject.toml": PYPROJECT.format(version=package_version())
    }
    for path in source_files():
        wanted[package_dir / path.name] = published_text(path)

    # A module deleted from the source has to leave the published tree too, or
    # the notebook keeps installing a package that still exports it.
    existing = set(package_dir.glob("*.py")) if package_dir.is_dir() else set()
    stale = sorted(existing - set(wanted))
    return wanted, stale


def differences(wanted: dict[Path, str], stale: list[Path]) -> list[str]:
    """Name every published file that does not match the source."""
    out = [f"stale, would be removed: {path.name}" for path in stale]
    for path, text in sorted(wanted.items()):
        if not path.exists():
            out.append(f"missing: {path.name}")
        elif path.read_text(encoding="utf-8") != text:
            out.append(f"differs: {path.name}")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="report whether the published copy is current and write nothing",
    )
    parser.add_argument(
        "--target",
        type=Path,
        default=DEFAULT_TARGET,
        help=f"directory to publish into (default: {DEFAULT_TARGET})",
    )
    args = parser.parse_args()

    if not SOURCE.is_dir():
        raise SystemExit(f"no package at {SOURCE}")
    if not args.check and not args.target.parent.is_dir():
        raise SystemExit(
            f"{args.target.parent} does not exist. Clone the workshop repository "
            f"beside this one, or pass --target."
        )

    wanted, stale = plan(args.target)
    drift = differences(wanted, stale)

    if not drift:
        print(f"{args.target} is current with src/{PACKAGE}/")
        return 0

    if args.check:
        print(f"{args.target} is stale:", file=sys.stderr)
        for line in drift:
            print(f"  {line}", file=sys.stderr)
        print("Run ./scripts/sync_workshop_lab.py", file=sys.stderr)
        return 1

    for path in stale:
        path.unlink()
        print(f"removed {path.name}")
    for path, text in sorted(wanted.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"published {len(wanted)} files to {args.target}")
    print("Commit and push the workshop repository for the notebook to see them.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
